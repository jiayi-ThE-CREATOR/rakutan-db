"""授業内容タグの語彙と、タグを確定させる規則。

■ なにを解こうとしているか
学生は「面白いかどうか」を**内容**で判断する。たいていは科目名で分かるが、
科目名からは分からないのに中身が面白い授業がある。
例：「日本語の歴史」を扱う授業。大学の公式分類にそんな項目は無い。

だから `ことば・語学` と `歴史` を**両方**選ぶと届く、という作りにする。
交差は語彙に持たせず、**検索するときに生む**。

■ なぜ木ではなくフラットな複数ラベルか（語彙は小さいほうが強い）
    2階層の木（18大類×6小類・1科目1葉）  … 表現できる組み合わせ 108
    フラット31タグ・1科目1〜3個          … 31 + 465 + 4,495 ≒ 5,000
語彙は小さいのに表現力は40倍以上ある。
「キーワードを増やしすぎない」という要求を、木より**よく**満たす。

■ 語彙は人が固定する。AI は「選ぶ」だけで「作らない」
自由記述を許すと必ず数千語のロングテールが生えて、タグの重なりが消える。
`clean()` が最後の門で、語彙に無いキーはここで落ちる。

■ ナンバリング・学部からタグを作らない（却下した案）
`08MEEN→機械` `04MATH→数学` は一見きれいだが、実測するとそうやって作った
ラベルの **77% が「1学部で90%以上」** ―― `category` が既に持っている情報の
言い換えでしかなく、学部フィルタと重複するだけだった。
学部・ナンバリングは AI への**入力**（文脈）には使ってよいが、**出力ラベルにはしない**。

設計は docs/plans/2026-09-03-naiyou-tag-design.md
"""

from __future__ import annotations

import re

# ── 語彙 ────────────────────────────────────────
# 学問名ではなく**学生の言葉**にする。score.py が内部の attendance を画面では
# 「出席の緩さ」と出しているのと同じ原則。この層の目的は正確な分類ではなく、
# 「面白そう」と思わせることなので、「神経科学」ではなく「脳・神経」と書く。
#
# 増やすときは tools/subject_survey.py の3表を見てから。1タグあたりの科目が
# 減るほど、組み合わせで掘ったときに0件になりやすくなる。
