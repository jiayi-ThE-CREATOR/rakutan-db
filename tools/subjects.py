# ── レンズタグ ──────────────────────────────────
# 単独で成立する授業は少なく、ほぼ常に他のタグに乗る
# （日本語の**歴史**／**環境**経済学／**ジェンダー**と法）。
# **組み合わせ検索が成立するのは、この5つがあるから。**
# 「歴史学という学部は無い」を理由に落とすと、この設計の中心が消える。
LENS = ("rekishi", "bunka", "gender", "kankyo", "kokusai")

# 1科目に付けるタグの上限。増やすと「とりあえず全部付ける」に寄り、
# タグが絞り込みの役に立たなくなる。
MAX_TAGS = 3


# ── 科目名ルール（語学だけ） ──────────────────────
# 実データで科目名に言語名を含むのは 2,479件。ここは AI を呼ばずに確定できる。
#
# 🚨 **「外国語学部だから語学」と倒さないこと。** 外国語学部2,040件のうち
# 822件は言語名を含まない地域研究の科目（【専攻科目】アフリカ地域文化演習a 等）で、
# 文化・地域／国際 の側に寄る。学部から倒すのは、上の「却下した案」そのもの。
# だから見るのは**科目名に言語名があるか**だけにする。
LANGUAGES = (
    "英語", "ドイツ語", "フランス語", "中国語", "朝鮮語", "韓国語", "ロシア語",
    "スペイン語", "イタリア語", "日本語", "ラテン語", "アラビア語", "ヒンディー",
    "トルコ語", "ペルシア語", "スワヒリ", "ポルトガル語", "タイ語", "ベトナム語",
    "インドネシア語", "モンゴル語", "ビルマ語", "フィリピノ", "ウルドゥ",
    "デンマーク語", "スウェーデン語", "ハンガリー語", "ギリシア語",
)
_LANG_RE = re.compile("|".join(map(re.escape, LANGUAGES)))


def from_title(title: str | None) -> list[str]:
    """科目名だけから確実に言えるタグ。言えないことは言わない。"""
    return ["kotoba"] if _LANG_RE.search(title or "") else []


def clean(tags) -> list[str]:
    """語彙に無いキーを落とし、重複を消し、語彙の定義順に並べて上限で切る。

    **AI が語彙を作るのを防ぐ最後の門。** ここを緩めると、モデルが返した
    「にほんごのれきし」のような自由記述がそのまま画面に出る。
    並びを語彙の定義順に固定するのは、同じ集合が毎回同じ順で出るようにするため
    （順が揺れると差分が読めない）。
    """
    if not tags:
        return []
    seen = {t for t in tags if t in VOCAB}
    return [k for k in VOCAB if k in seen][:MAX_TAGS]


def merge(manual=None, title=None, ai=None) -> tuple[list[str], str | None]:
    """出所の優先順位を適用して、最終的なタグと出所を返す。

    **人が書いた行は AI に勝つ。** 品質ゲートで見つけた誤りを直したのに
    次の実行で上書きされる、という状態を作らない。

    科目名ルールと AI は**合流させる**（どちらかを捨てない）。語学の科目にも
    `文化・地域` や `歴史` が追加で付きうるので、`ことば・語学` は確定として
    AI に渡し、残りの枠を AI に判断させる。
    """
    m = clean(manual)
    if m:
        return m, "manual"
    t, a = clean(title), clean(ai)
    merged = clean(t + a)
    if not merged:
        return [], None
    return merged, "ai" if a else "title"


def vocab_prompt() -> str:
    """AI に渡す語彙の一覧。**ここが唯一の定義**で、プロンプト側に書き写さない。

    書き写すと語彙を足したときにプロンプトだけ古くなり、
    モデルが知らないキーを返して clean() に黙って落とされる
    （＝タグが付かない科目が増えるだけで、原因が画面から見えない）。
    """
    lines = "\n".join(f"  {k} = {label}" for k, label in VOCAB.items())
    return (
        f"次の一覧から、この授業の内容に当てはまるものを最大{MAX_TAGS}個選び、\n"
        "キー（左側の英字）だけをカンマ区切りで返してください。\n"
        "当てはまるものが無ければ空行を返してください。\n"
        "一覧に無い語を作ってはいけません。\n\n"
        f"{lines}\n"
    )
